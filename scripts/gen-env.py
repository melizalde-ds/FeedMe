"""Write .env with a fresh JWT secret and the two Supabase API keys signed with it."""

import base64
import hashlib
import hmac
import json
import secrets
import time
from pathlib import Path

ENV_FILE = Path(__file__).resolve().parent.parent / ".env"
TEN_YEARS = 10 * 365 * 24 * 60 * 60


def b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def sign_key(role: str, secret: str) -> str:
    now = int(time.time())
    header = b64(json.dumps({"alg": "HS256", "typ": "JWT"}).encode())
    claims = {"role": role, "iss": "supabase-dev", "iat": now, "exp": now + TEN_YEARS}
    body = f"{header}.{b64(json.dumps(claims).encode())}"
    signature = hmac.new(secret.encode(), body.encode(), hashlib.sha256).digest()
    return f"{body}.{b64(signature)}"


if ENV_FILE.exists():
    raise SystemExit(f"{ENV_FILE} already exists - delete it first to regenerate.")

secret = secrets.token_hex(32)
ENV_FILE.write_text(
    "# Local dev secrets - generated by scripts/gen-env.py, do not commit.\n"
    f"SUPABASE_JWT_SECRET={secret}\n"
    "# Safe for the browser.\n"
    f"SUPABASE_ANON_KEY={sign_key('anon', secret)}\n"
    "# Bypasses row level security - server side only.\n"
    f"SUPABASE_SERVICE_ROLE_KEY={sign_key('service_role', secret)}\n"
)
print(f"Wrote {ENV_FILE}")
